// USB HID usage -> Windows virtual-key, for turning the keyboard layout into
// host-side triggers. Fn (0xFF) has no VK: the board handles Fn in firmware and
// it never reaches Windows.

const TABLE: Record<number, number> = {
  0x28: 0x0d, 0x29: 0x1b, 0x2a: 0x08, 0x2b: 0x09, 0x2c: 0x20,
  0x2d: 0xbd, 0x2e: 0xbb, 0x2f: 0xdb, 0x30: 0xdd, 0x31: 0xdc,
  0x33: 0xba, 0x34: 0xde, 0x35: 0xc0, 0x36: 0xbc, 0x37: 0xbe,
  0x38: 0xbf, 0x39: 0x14,
  0x46: 0x2c, 0x47: 0x91, 0x48: 0x13,
  0x49: 0x2d, 0x4a: 0x24, 0x4b: 0x21, 0x4c: 0x2e, 0x4d: 0x23, 0x4e: 0x22,
  0x4f: 0x27, 0x50: 0x25, 0x51: 0x28, 0x52: 0x26,
  0x53: 0x90, 0x54: 0x6f, 0x55: 0x6a, 0x56: 0x6d, 0x57: 0x6b, 0x58: 0x0d,
  0x63: 0x6e,
  0xe0: 0xa2, 0xe1: 0xa0, 0xe2: 0xa4, 0xe3: 0x5b,
  0xe4: 0xa3, 0xe5: 0xa1, 0xe6: 0xa5, 0xe7: 0x5c,
}

export function hidToVk(hid: number): number | null {
  if (hid >= 0x04 && hid <= 0x1d) return 0x41 + (hid - 0x04) // A-Z
  if (hid >= 0x1e && hid <= 0x26) return 0x31 + (hid - 0x1e) // 1-9
  if (hid === 0x27) return 0x30 // 0
  if (hid >= 0x3a && hid <= 0x45) return 0x70 + (hid - 0x3a) // F1-F12
  if (hid >= 0x59 && hid <= 0x61) return 0x61 + (hid - 0x59) // numpad 1-9
  if (hid === 0x62) return 0x60 // numpad 0
  return TABLE[hid] ?? null
}
